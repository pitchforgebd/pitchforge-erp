import { z } from 'zod';

import { command, createOne, getOne, listOf, updateOne } from '../endpoint-helpers.ts';
import { IdParams, defineEndpoints } from '../endpoint.ts';
import { Uuid } from '../shared/primitives.ts';

import {
  AwardTender,
  ClientAccount,
  ClientContact,
  ClientOverview,
  Contract,
  ContractStatus,
  CreateClientAccount,
  CreateClientContact,
  CreateContract,
  CreateGuarantee,
  CreateLead,
  CreateOpportunity,
  CreateQuotation,
  CreateSalesActivity,
  CreateStandardDocument,
  CreateTender,
  DuplicateMatch,
  Guarantee,
  GuaranteeKind,
  Lead,
  LeadStatus,
  LoseOpportunity,
  MoveOpportunity,
  Opportunity,
  OpportunityStatus,
  PipelineStage,
  Quotation,
  QuotationStatus,
  ReplacePipelineStages,
  ReplaceTenderChecklist,
  SalesActivity,
  SalesForecast,
  StandardDocument,
  Tender,
  TenderChecklistItem,
  TenderOutcome,
  TenderStatus,
  UpdateClientAccount,
  UpdateContract,
  UpdateLead,
  UpdateOpportunity,
  UpdateQuotation,
  UpdateTender,
  WinOpportunity,
} from './schemas.ts';

const CRM = '/api/v1/crm';

export const crmEndpoints = defineEndpoints('crm', {
  /* Leads and clients -------------------------------------------------------------------------- */
  listLeads: listOf(`${CRM}/leads`, 'Leads', ['CRM-01'], Lead, {
    status: LeadStatus.optional(),
    ownerId: Uuid.optional(),
  }),
  getLead: getOne(`${CRM}/leads/{id}`, 'One lead', ['CRM-01'], Lead),
  createLead: createOne(`${CRM}/leads`, 'Add a lead', ['CRM-01'], CreateLead, Lead),
  updateLead: updateOne(`${CRM}/leads/{id}`, 'Update a lead', ['CRM-01'], UpdateLead, Lead),
  convertLead: command(
    `${CRM}/leads/{id}:convert`,
    'Convert a lead to a client and contact',
    ['CRM-02'],
    ClientAccount,
  ),
  findDuplicates: {
    method: 'GET',
    path: `${CRM}/duplicates`,
    summary: 'Possible duplicates by name, phone, email or TIN',
    featureIds: ['CRM-03'],
    query: z.strictObject({
      name: z.string().max(200).optional(),
      phone: z.string().max(30).optional(),
      email: z.string().max(254).optional(),
      tin: z.string().max(12).optional(),
    }),
    response: z.object({ items: z.array(DuplicateMatch) }),
  },
  listClients: listOf(`${CRM}/clients`, 'Client accounts', ['CRM-04'], ClientAccount, {
    q: z.string().max(100).optional(),
  }),
  getClient: getOne(`${CRM}/clients/{id}`, 'One client', ['CRM-04'], ClientAccount),
  createClient: createOne(
    `${CRM}/clients`,
    'Add a client',
    ['CRM-04'],
    CreateClientAccount,
    ClientAccount,
  ),
  updateClient: updateOne(
    `${CRM}/clients/{id}`,
    'Update a client',
    ['CRM-04'],
    UpdateClientAccount,
    ClientAccount,
  ),
  getClientOverview: getOne(
    `${CRM}/clients/{id}/overview`,
    'Client 360: contacts, activity, pipeline, receivable, projects',
    ['CRM-07'],
    ClientOverview,
  ),
  listClientContacts: getOne(
    `${CRM}/clients/{id}/contacts`,
    'Contacts of one client',
    ['CRM-05'],
    z.object({ items: z.array(ClientContact) }),
  ),
  addClientContact: {
    ...createOne(
      `${CRM}/clients/{id}/contacts`,
      'Add a contact to a client',
      ['CRM-05'],
      CreateClientContact,
      ClientContact,
    ),
    params: IdParams,
    versioned: false,
  },
  listActivities: listOf(
    `${CRM}/activities`,
    'Calls, meetings and notes',
    ['CRM-06'],
    SalesActivity,
    {
      clientId: Uuid.optional(),
      opportunityId: Uuid.optional(),
    },
  ),
  createActivity: createOne(
    `${CRM}/activities`,
    'Log an activity, with an optional follow-up reminder',
    ['CRM-06'],
    CreateSalesActivity,
    SalesActivity,
  ),

  /* Pipeline ------------------------------------------------------------------------------------ */
  listPipelineStages: {
    method: 'GET',
    path: `${CRM}/pipeline-stages`,
    summary: 'Pipeline stages',
    featureIds: ['CRM-10'],
    response: z.object({ items: z.array(PipelineStage) }),
  },
  replacePipelineStages: {
    method: 'PUT',
    path: `${CRM}/pipeline-stages`,
    summary: 'Replace the pipeline stages',
    featureIds: ['CRM-10'],
    body: ReplacePipelineStages,
    response: z.object({ items: z.array(PipelineStage) }),
  },
  listOpportunities: listOf(
    `${CRM}/opportunities`,
    'Opportunities, for the board and the list',
    ['CRM-09', 'CRM-12'],
    Opportunity,
    { status: OpportunityStatus.optional(), ownerId: Uuid.optional(), stageId: Uuid.optional() },
  ),
  getOpportunity: getOne(`${CRM}/opportunities/{id}`, 'One opportunity', ['CRM-09'], Opportunity),
  createOpportunity: createOne(
    `${CRM}/opportunities`,
    'Add an opportunity',
    ['CRM-09'],
    CreateOpportunity,
    Opportunity,
  ),
  updateOpportunity: updateOne(
    `${CRM}/opportunities/{id}`,
    'Update an opportunity',
    ['CRM-09'],
    UpdateOpportunity,
    Opportunity,
  ),
  moveOpportunity: {
    ...command(
      `${CRM}/opportunities/{id}:move`,
      'Move to a stage',
      ['CRM-10', 'CRM-12'],
      Opportunity,
    ),
    body: MoveOpportunity,
  },
  winOpportunity: {
    ...command(
      `${CRM}/opportunities/{id}:win`,
      'Mark won; the project is created by the opportunity.won event',
      ['CRM-14'],
      Opportunity,
    ),
    body: WinOpportunity,
  },
  loseOpportunity: {
    ...command(
      `${CRM}/opportunities/{id}:lose`,
      'Mark lost, with the reason and competitor',
      ['CRM-11'],
      Opportunity,
    ),
    body: LoseOpportunity,
  },
  getSalesForecast: {
    method: 'GET',
    path: `${CRM}/forecast`,
    summary: 'Weighted sales forecast by month',
    featureIds: ['CRM-13'],
    response: SalesForecast,
  },

  /* Quotations and contracts ---------------------------------------------------------------------- */
  listQuotations: listOf(`${CRM}/quotations`, 'Quotations', ['CRM-15'], Quotation, {
    status: QuotationStatus.optional(),
    clientId: Uuid.optional(),
  }),
  getQuotation: getOne(`${CRM}/quotations/{id}`, 'One quotation', ['CRM-15'], Quotation),
  createQuotation: createOne(
    `${CRM}/quotations`,
    'Draft a quotation',
    ['CRM-15'],
    CreateQuotation,
    Quotation,
  ),
  updateQuotation: updateOne(
    `${CRM}/quotations/{id}`,
    'Change a draft quotation',
    ['CRM-15'],
    UpdateQuotation,
    Quotation,
  ),
  submitQuotation: command(
    `${CRM}/quotations/{id}:submit`,
    'Submit; a discount above the limit goes for approval',
    ['CRM-17'],
    Quotation,
  ),
  newQuotationVersion: {
    ...command(
      `${CRM}/quotations/{id}:new-version`,
      'Start a new revision; the old one is kept',
      ['CRM-16'],
      Quotation,
    ),
    status: 201,
  },
  sendQuotation: {
    ...command(`${CRM}/quotations/{id}:send`, 'Email the quotation', ['CRM-15'], Quotation),
    sendsMessages: true,
  },
  acceptQuotation: command(
    `${CRM}/quotations/{id}:accept`,
    'Record that the client accepted',
    ['CRM-15'],
    Quotation,
  ),
  listContracts: listOf(`${CRM}/contracts`, 'Contracts', ['CRM-18', 'CRM-19'], Contract, {
    status: ContractStatus.optional(),
    clientId: Uuid.optional(),
  }),
  getContract: getOne(`${CRM}/contracts/{id}`, 'One contract', ['CRM-18'], Contract),
  createContract: createOne(
    `${CRM}/contracts`,
    'Add a contract',
    ['CRM-18'],
    CreateContract,
    Contract,
  ),
  updateContract: updateOne(
    `${CRM}/contracts/{id}`,
    'Update a contract, including its renewal date',
    ['CRM-18', 'CRM-19'],
    UpdateContract,
    Contract,
  ),

  /* Tenders ------------------------------------------------------------------------------------- */
  listTenders: listOf(`${CRM}/tenders`, 'Tender register', ['TND-01', 'TND-02'], Tender, {
    status: TenderStatus.optional(),
  }),
  getTender: getOne(`${CRM}/tenders/{id}`, 'One tender', ['TND-01'], Tender),
  createTender: createOne(
    `${CRM}/tenders`,
    'Register a tender, with its deadlines and team',
    ['TND-01', 'TND-02', 'TND-06'],
    CreateTender,
    Tender,
  ),
  updateTender: updateOne(
    `${CRM}/tenders/{id}`,
    'Update a tender',
    ['TND-01', 'TND-02', 'TND-06'],
    UpdateTender,
    Tender,
  ),
  recordTenderOutcome: {
    ...command(
      `${CRM}/tenders/{id}:record-outcome`,
      'Record the result, rank and winning price',
      ['TND-11'],
      Tender,
    ),
    body: TenderOutcome,
  },
  awardTender: {
    ...command(
      `${CRM}/tenders/{id}:award`,
      'Create the contract; the project follows from the tender.awarded event',
      ['TND-14'],
      Tender,
    ),
    body: AwardTender,
  },
  getTenderChecklist: getOne(
    `${CRM}/tenders/{id}/checklist`,
    'Bid document checklist',
    ['TND-04'],
    z.object({ items: z.array(TenderChecklistItem) }),
  ),
  replaceTenderChecklist: {
    method: 'PUT',
    path: `${CRM}/tenders/{id}/checklist`,
    summary: 'Replace the bid document checklist',
    featureIds: ['TND-04'],
    params: IdParams,
    versioned: false,
    body: ReplaceTenderChecklist,
    response: z.object({ items: z.array(TenderChecklistItem) }),
  },
  listStandardDocuments: listOf(
    `${CRM}/standard-documents`,
    'Reusable bid documents, with their expiry',
    ['TND-05'],
    StandardDocument,
  ),
  createStandardDocument: createOne(
    `${CRM}/standard-documents`,
    'Add a reusable bid document',
    ['TND-05'],
    CreateStandardDocument,
    StandardDocument,
  ),
  listGuarantees: listOf(
    `${CRM}/guarantees`,
    'Bid security, performance guarantees and margin money',
    ['TND-08', 'TND-09', 'TND-10'],
    Guarantee,
    { kind: GuaranteeKind.optional(), tenderId: Uuid.optional() },
  ),
  getGuarantee: getOne(`${CRM}/guarantees/{id}`, 'One guarantee', ['TND-08'], Guarantee),
  createGuarantee: createOne(
    `${CRM}/guarantees`,
    'Record a guarantee or margin money',
    ['TND-08', 'TND-09', 'TND-10'],
    CreateGuarantee,
    Guarantee,
  ),
  releaseGuarantee: command(
    `${CRM}/guarantees/{id}:release`,
    'Record that a guarantee was released',
    ['TND-08', 'TND-09', 'TND-10'],
    Guarantee,
  ),
});
