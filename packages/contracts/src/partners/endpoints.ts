import { z } from 'zod';

import { PartyStatement } from '../accounting/payables.ts';
import { IdParams, defineEndpoints } from '../endpoint.ts';
import { listQuery, page } from '../shared/pagination.ts';
import { IsoDate, Uuid } from '../shared/primitives.ts';

import {
  CreateDistributionRun,
  CreateEquityVersion,
  CreatePartner,
  CreatePartnerTransaction,
  DistributionRun,
  DistributionRunStatus,
  EquityVersion,
  Partner,
  PartnerTransaction,
  PartnerTransactionStatus,
  PartnerTransactionType,
  ReverseDistributionRun,
  UpdatePartner,
  UpdatePartnerTransaction,
  WithdrawableBalance,
} from './schemas.ts';

const POSTING_ERRORS = ['PERIOD_LOCKED', 'NOT_BALANCED', 'INVALID_STATE'] as const;

export const partnersEndpoints = defineEndpoints('partners', {
  listPartners: {
    method: 'GET',
    path: '/api/v1/partners/partners',
    summary: 'Partner register; balances are omitted without field permission',
    featureIds: ['PAR-01'],
    list: true,
    query: listQuery({ active: z.stringbool().optional() }),
    response: page(Partner),
  },
  getPartner: {
    method: 'GET',
    path: '/api/v1/partners/partners/{id}',
    summary: 'One partner',
    featureIds: ['PAR-01'],
    params: IdParams,
    response: Partner,
  },
  createPartner: {
    method: 'POST',
    path: '/api/v1/partners/partners',
    summary: 'Add a partner',
    featureIds: ['PAR-01'],
    stepUp: true,
    body: CreatePartner,
    status: 201,
    response: Partner,
  },
  updatePartner: {
    method: 'PATCH',
    path: '/api/v1/partners/partners/{id}',
    summary: 'Change a partner’s name or linked user',
    featureIds: ['PAR-01'],
    params: IdParams,
    stepUp: true,
    body: UpdatePartner,
    response: Partner,
  },
  getWithdrawableBalance: {
    method: 'GET',
    path: '/api/v1/partners/partners/{id}/withdrawable-balance',
    summary: 'What the partner may draw now, with a warning',
    featureIds: ['PAR-14'],
    params: IdParams,
    response: WithdrawableBalance,
  },
  getPartnerStatement: {
    method: 'GET',
    path: '/api/v1/partners/partners/{id}/statement',
    summary: 'Partner statement for a date range; the PDF comes from core documents:render',
    featureIds: ['PAR-15'],
    params: IdParams,
    query: z.strictObject({ from: IsoDate, to: IsoDate }),
    response: PartyStatement,
  },

  listEquityVersions: {
    method: 'GET',
    path: '/api/v1/partners/equity-versions',
    summary: 'Effective-dated equity history',
    featureIds: ['PAR-02'],
    list: true,
    query: listQuery({}),
    response: page(EquityVersion),
  },
  createEquityVersion: {
    method: 'POST',
    path: '/api/v1/partners/equity-versions',
    summary: 'Change equity from a date; shares must total 100%',
    featureIds: ['PAR-02'],
    stepUp: true,
    body: CreateEquityVersion,
    status: 201,
    response: EquityVersion,
    errors: ['EQUITY_NOT_100_PERCENT', 'INVALID_STATE'],
  },

  listPartnerTransactions: {
    method: 'GET',
    path: '/api/v1/partners/partner-transactions',
    summary: 'Capital, drawings, returns, loans, remuneration and money held personally',
    featureIds: ['PAR-03', 'PAR-04', 'PAR-05', 'PAR-06', 'PAR-07', 'PAR-08'],
    list: true,
    query: listQuery({
      partnerId: Uuid.optional(),
      type: PartnerTransactionType.optional(),
      status: PartnerTransactionStatus.optional(),
    }),
    response: page(PartnerTransaction),
  },
  getPartnerTransaction: {
    method: 'GET',
    path: '/api/v1/partners/partner-transactions/{id}',
    summary: 'One partner transaction',
    featureIds: ['PAR-03', 'PAR-04', 'PAR-05', 'PAR-06', 'PAR-07', 'PAR-08'],
    params: IdParams,
    response: PartnerTransaction,
  },
  createPartnerTransaction: {
    method: 'POST',
    path: '/api/v1/partners/partner-transactions',
    summary: 'Draft a partner transaction',
    featureIds: ['PAR-03', 'PAR-04', 'PAR-05', 'PAR-06', 'PAR-07', 'PAR-08'],
    body: CreatePartnerTransaction,
    status: 201,
    response: PartnerTransaction,
  },
  updatePartnerTransaction: {
    method: 'PATCH',
    path: '/api/v1/partners/partner-transactions/{id}',
    summary: 'Change a draft partner transaction',
    featureIds: ['PAR-03', 'PAR-04', 'PAR-05', 'PAR-06', 'PAR-07', 'PAR-08'],
    params: IdParams,
    body: UpdatePartnerTransaction,
    response: PartnerTransaction,
    errors: ['INVALID_STATE'],
  },
  submitPartnerTransaction: {
    method: 'POST',
    path: '/api/v1/partners/partner-transactions/{id}:submit',
    summary: 'Send for approval; a drawing above the threshold needs all other partners',
    featureIds: ['PAR-04', 'PAR-09', 'PAR-14'],
    params: IdParams,
    stepUp: true,
    response: PartnerTransaction,
    errors: ['INSUFFICIENT_WITHDRAWABLE_BALANCE', 'PERIOD_LOCKED', 'INVALID_STATE'],
  },

  listDistributionRuns: {
    method: 'GET',
    path: '/api/v1/partners/distribution-runs',
    summary: 'Profit distribution runs',
    featureIds: ['PAR-10'],
    list: true,
    query: listQuery({ status: DistributionRunStatus.optional() }),
    response: page(DistributionRun),
  },
  getDistributionRun: {
    method: 'GET',
    path: '/api/v1/partners/distribution-runs/{id}',
    summary: 'One distribution run with its shares',
    featureIds: ['PAR-10', 'PAR-13'],
    params: IdParams,
    response: DistributionRun,
  },
  previewDistributionRun: {
    method: 'POST',
    path: '/api/v1/partners/distribution-runs',
    summary: 'Calculate a preview: reserve, then a day-weighted split by equity',
    featureIds: ['PAR-10', 'PAR-11', 'PAR-13'],
    body: CreateDistributionRun,
    status: 201,
    response: DistributionRun,
    errors: ['PERIOD_LOCKED', 'INVALID_STATE'],
  },
  postDistributionRun: {
    method: 'POST',
    path: '/api/v1/partners/distribution-runs/{id}:post',
    summary: 'Post the distribution to the ledger',
    featureIds: ['PAR-10'],
    params: IdParams,
    movesMoney: true,
    stepUp: true,
    response: DistributionRun,
    errors: ['SOD_VIOLATION', ...POSTING_ERRORS],
  },
  reverseDistributionRun: {
    method: 'POST',
    path: '/api/v1/partners/distribution-runs/{id}:reverse',
    summary: 'Reverse a whole run',
    featureIds: ['PAR-13'],
    params: IdParams,
    movesMoney: true,
    stepUp: true,
    body: ReverseDistributionRun,
    response: DistributionRun,
    errors: ['SOD_VIOLATION', 'ALREADY_REVERSED', ...POSTING_ERRORS],
  },
});
